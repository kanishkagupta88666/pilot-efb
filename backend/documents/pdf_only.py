"""Bring a PDF-only document into the same structure as an XML manual.

Some documents (the bulletins) exist only as PDF: there is no XML and no
client node ID. This module reads such a PDF's structure, gives every
section and paragraph an ID, and stores it as Document > DocumentVersion >
DocumentNode, so search, the reader, revision comparison and the PDF overlay
work on it unchanged.

Reading the PDF
---------------
The sample bulletins are generated by ReportLab: each paragraph is drawn as
its own text block, and fonts tell the parts apart (title 16 pt bold, section
headings 13 pt bold, body 9.5 pt, running header and footer below 8 pt). The
outline lists the section headings and is cross-checked against them. A
paragraph split across a page break is joined back when the first part does
not end a sentence.

Derived IDs
-----------
These IDs are created here, not supplied by the client, and every revision
records ``derivedIds: true``. To keep them stable, a new revision is matched
against the previous one: sections by their text, then paragraphs within a
matched section by word similarity, in order. A section or paragraph that is
still recognisably the same keeps its ID, so the ID-based revision comparison
reports it as unchanged or modified rather than removed and added. Anything
new gets a new ID; an ID is never reused. Matching is by text, so it is an
approximation: a heavily rewritten paragraph is reported as removed + added,
and a paragraph moved to another section as removed in one, added in the other.
"""

from dataclasses import dataclass, field
from datetime import date
import difflib
import re
from pathlib import Path
from time import perf_counter

from django.db import DatabaseError, transaction
from django.utils import timezone
from pypdf import PdfReader

from documents.ingestion import (
    DocumentTreeIntegrityError,
    _anchor_records,
    _node_records,
    _require_unambiguous_ids,
    validate_version_tree,
)
from documents.models import ContentAnchor, Document, DocumentNode, DocumentVersion
from documents.xml_validation import PROJECT_ROOT

SOURCE = "pdf-only"
DOC_TYPE = "BULLETIN"
# Font sizes in the sample renditions (points).
TITLE_SIZE = 16.0
HEADING_SIZE = 13.0
FURNITURE_MAX_SIZE = 8.0
# Word-level similarity at which two paragraphs (or sections) count as the same.
PARAGRAPH_MATCH = 0.6
SECTION_MATCH = 0.5

_META = re.compile(
    r"Applicability:\s*(?P<applicability>.+?)\s+Effective\s+(?P<effective>\d{4}-\d{2}-\d{2})"
    r"(?:\s+Owner:\s*(?P<owner>.+))?$"
)
_SENTENCE_END = re.compile(r"[.!?:)\]]$")
_ID_NUMBER = re.compile(r"-pdf-[tp](\d+)$")


class PdfStructureError(ValueError):
    """The PDF does not have the structure this reader understands."""


@dataclass
class ParsedSection:
    title: str
    page: int
    paragraphs: list[str] = field(default_factory=list)


@dataclass
class ParsedDocument:
    title: str
    applicability: str
    effective_date: str
    owner: str
    classification: str
    sections: list[ParsedSection]


@dataclass
class _Block:
    page: int
    font: str
    size: float
    x: float
    text: str


def _blocks(reader: PdfReader) -> list[_Block]:
    """Text blocks in drawing order: one per paragraph, heading or line of furniture."""
    blocks: list[_Block] = []
    for number, page in enumerate(reader.pages, start=1):
        last_key = None

        def visit(text, cm, tm, font, size, number=number):
            nonlocal last_key
            if not text:
                return
            name = (font or {}).get("/BaseFont", "") if font else ""
            key = (tuple(round(value, 1) for value in cm), name, round(size, 1))
            if blocks and key == last_key and blocks[-1].page == number:
                blocks[-1].text += text
            else:
                blocks.append(_Block(number, str(name), round(size, 1), round(tm[4], 1), text))
            last_key = key

        page.extract_text(visitor_text=visit)
    for block in blocks:
        block.text = " ".join(block.text.split())
    return [block for block in blocks if block.text]


def _outline_titles(reader: PdfReader) -> list[str]:
    titles: list[str] = []

    def walk(items) -> None:
        for item in items:
            if isinstance(item, list):
                walk(item)
            else:
                titles.append(" ".join(item.title.split()))

    walk(reader.outline)
    return titles


def parse_pdf(path: str | Path) -> ParsedDocument:
    reader = PdfReader(path)
    title = ""
    applicability = effective = owner = ""
    classification = ""
    sections: list[ParsedSection] = []
    continues = False  # the last paragraph stopped mid-sentence at a page break

    for block in _blocks(reader):
        bold = "Bold" in block.font
        if block.size < FURNITURE_MAX_SIZE:
            if "NOT FOR OPERATIONAL USE" in block.text.upper():
                classification = block.text
            continue
        if bold and block.size >= TITLE_SIZE:
            title = f"{title} {block.text}".strip()
            continue
        if bold and block.size >= HEADING_SIZE:
            sections.append(ParsedSection(title=block.text, page=block.page))
            continues = False
            continue
        if not sections:
            match = _META.match(block.text)
            if match:
                applicability = match["applicability"].strip()
                effective = match["effective"]
                owner = (match["owner"] or "").strip()
            # Anything else before the first section is front matter.
            continue
        paragraphs = sections[-1].paragraphs
        if continues and paragraphs:
            paragraphs[-1] = f"{paragraphs[-1]} {block.text}"
        else:
            paragraphs.append(block.text)
        continues = not _SENTENCE_END.search(paragraphs[-1])

    if not title or not sections:
        raise PdfStructureError("No title or section headings were found.")
    if not effective:
        raise PdfStructureError("No 'Applicability … Effective YYYY-MM-DD' line was found.")
    outline = _outline_titles(reader)
    headings = [section.title for section in sections]
    if outline != headings:
        raise PdfStructureError(
            "The PDF outline does not match the section headings on the pages."
        )
    if any(not section.paragraphs for section in sections):
        raise PdfStructureError("A section has no text.")
    return ParsedDocument(
        title=title,
        applicability=applicability,
        effective_date=effective,
        owner=owner,
        classification=classification or "SYNTHETIC SAMPLE - NOT FOR OPERATIONAL USE",
        sections=sections,
    )


def _words(text: str) -> list[str]:
    return text.lower().split()


def similarity(left: str, right: str) -> float:
    return difflib.SequenceMatcher(a=_words(left), b=_words(right), autojunk=False).ratio()


def align(old: list[str], new: list[str], threshold: float) -> dict[int, int]:
    """Pair new items with old ones, in order. Returns {new index: old index}.

    Identical runs are paired directly. Where the two lists differ, each new
    item takes the most similar remaining old item at or above ``threshold``,
    keeping the order, so nothing is paired across an earlier pairing.
    """
    matcher = difflib.SequenceMatcher(
        a=[" ".join(_words(text)) for text in old],
        b=[" ".join(_words(text)) for text in new],
        autojunk=False,
    )
    pairs: dict[int, int] = {}
    for tag, old_start, old_end, new_start, new_end in matcher.get_opcodes():
        if tag == "equal":
            for offset in range(new_end - new_start):
                pairs[new_start + offset] = old_start + offset
        elif tag == "replace":
            cursor = old_start
            for new_index in range(new_start, new_end):
                best: tuple[int, float] | None = None
                for old_index in range(cursor, old_end):
                    score = similarity(old[old_index], new[new_index])
                    if score >= threshold and (best is None or score > best[1]):
                        best = (old_index, score)
                if best is not None:
                    pairs[new_index] = best[0]
                    cursor = best[0] + 1
    return pairs


@dataclass
class _PreviousSection:
    id: str
    text: str
    paragraphs: list[tuple[str, str]]  # (id, text)


def _previous_structure(version: DocumentVersion) -> list[_PreviousSection]:
    sections = []
    for node in version.nodes.filter(node_type=DocumentNode.NodeType.TOPIC).order_by("position"):
        paragraphs = [
            (block["id"], "".join(segment["text"] for segment in block["segments"]))
            for block in node.content_blocks or ()
        ]
        sections.append(
            _PreviousSection(node.node_id, " ".join(text for _, text in paragraphs), paragraphs)
        )
    return sections


def _highest_id_number(document_id: str) -> int:
    """The largest derived ID number ever used for this document, in any revision."""
    highest = 0
    for version in DocumentVersion.objects.filter(document_id=document_id):
        for node in version.nodes.all():
            for identifier in [node.node_id, *(b["id"] for b in node.content_blocks or ())]:
                match = _ID_NUMBER.search(identifier)
                if match:
                    highest = max(highest, int(match[1]))
    return highest


def assign_ids(
    parsed: ParsedDocument,
    previous: list[_PreviousSection],
    slug: str,
    next_number: int,
) -> list[tuple[str, ParsedSection, list[str]]]:
    """Give each section and paragraph an ID, keeping the previous one when matched."""
    counter = next_number

    def new_id(kind: str) -> str:
        nonlocal counter
        counter += 1
        return f"{slug}-pdf-{kind}{counter:04d}"

    section_pairs = align(
        [section.text for section in previous],
        [" ".join(section.paragraphs) for section in parsed.sections],
        SECTION_MATCH,
    )
    result = []
    for index, section in enumerate(parsed.sections):
        old = previous[section_pairs[index]] if index in section_pairs else None
        section_id = old.id if old else new_id("t")
        paragraph_ids: list[str] = []
        pairs = (
            align([text for _, text in old.paragraphs], section.paragraphs, PARAGRAPH_MATCH)
            if old
            else {}
        )
        for paragraph_index in range(len(section.paragraphs)):
            if paragraph_index in pairs:
                paragraph_ids.append(old.paragraphs[pairs[paragraph_index]][0])
            else:
                paragraph_ids.append(new_id("p"))
        result.append((section_id, section, paragraph_ids))
    return result


def _slug(document_id: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", document_id.lower()).strip("-")


def document_id_for(path: Path) -> str:
    """Bulletin_26-01.pdf -> BULLETIN-26-01."""
    return re.sub(r"[^A-Z0-9]+", "-", path.stem.upper().split("_REV")[0]).strip("-")


@dataclass
class PdfIngestionResult:
    success: bool
    document_id: str | None
    revision: int | None
    sections: int = 0
    paragraphs: int = 0
    kept_ids: int = 0
    new_ids: int = 0
    message: str | None = None
    elapsed_seconds: float = 0.0


def ingest_pdf_only(
    pdf_path: str | Path,
    *,
    document_id: str | None = None,
    revision: int | None = None,
    revision_date: str | None = None,
    change_summary: str | None = None,
    replace: bool = False,
) -> PdfIngestionResult:
    """Read one PDF-only revision and store it like an XML revision.

    The PDF must live inside the project (sample data or test fixtures), since
    the reader serves it from the stored path.
    """
    started = perf_counter()
    path = Path(pdf_path).resolve()
    try:
        relative = path.relative_to(PROJECT_ROOT)
    except ValueError:
        return PdfIngestionResult(False, None, None, message="The PDF must be inside the project folder.")
    document_id = document_id or document_id_for(path)
    try:
        parsed = parse_pdf(path)
    except PdfStructureError as error:
        return PdfIngestionResult(False, document_id, revision, message=f"Unreadable PDF structure: {error}")

    slug = _slug(document_id)
    try:
        with transaction.atomic():
            existing = DocumentVersion.objects.filter(document_id=document_id)
            if revision is None:
                latest = existing.order_by("-revision").first()
                revision = 0 if latest is None else latest.revision + 1
            if existing.filter(revision=revision).exists() and not replace:
                return PdfIngestionResult(
                    False, document_id, revision,
                    message=f"Document {document_id} revision {revision} already exists.",
                )
            previous_version = existing.filter(revision__lt=revision).order_by("-revision").first()
            previous = _previous_structure(previous_version) if previous_version else []
            assigned = assign_ids(parsed, previous, slug, _highest_id_number(document_id))
            previous_ids = {pid for section in previous for pid, _ in section.paragraphs}
            previous_ids |= {section.id for section in previous}

            metadata = {
                "docId": document_id,
                "title": parsed.title,
                "docType": DOC_TYPE,
                "applicability": parsed.applicability,
                "revision": revision,
                "revisionDate": revision_date or parsed.effective_date,
                "effectiveDate": parsed.effective_date,
                "owner": parsed.owner,
                "changeSummary": change_summary
                or "PDF-only document; structure and IDs derived from the PDF.",
                "classification": parsed.classification,
                "source": SOURCE,
                "derivedIds": True,
                "pdf": relative.as_posix(),
            }
            document, _ = Document.objects.get_or_create(
                id=document_id,
                defaults={"title": parsed.title, "doc_type": DOC_TYPE, "namespace": SOURCE},
            )
            document.title, document.doc_type, document.namespace = parsed.title, DOC_TYPE, SOURCE
            document.save(update_fields=("title", "doc_type", "namespace"))
            version, created = DocumentVersion.objects.update_or_create(
                document=document,
                revision=revision,
                defaults={
                    "revision_date": date.fromisoformat(metadata["revisionDate"]),
                    "effective_date": date.fromisoformat(parsed.effective_date),
                    "metadata": metadata,
                    "source_filename": path.name,
                    "ingested_at": timezone.now(),
                },
            )
            if not created:
                version.nodes.all().delete()

            chapters = [{
                "id": f"{slug}-pdf-c",
                "number": "1",
                "title": parsed.title,
                "sections": [{
                    "id": f"{slug}-pdf-s",
                    "number": "1.1",
                    "title": "Sections",
                    "topics": [
                        {"id": section_id, "number": str(index), "title": section.title}
                        for index, (section_id, section, _) in enumerate(assigned, start=1)
                    ],
                }],
            }]
            topics = {
                section_id: {
                    "blocks": [
                        {"type": "para", "id": pid, "segments": [{"type": "text", "text": text}]}
                        for pid, text in zip(paragraph_ids, section.paragraphs)
                    ]
                }
                for section_id, section, paragraph_ids in assigned
            }
            chapter_records, section_records, topic_records = _node_records(version, chapters, topics)
            DocumentNode.objects.bulk_create(chapter_records)
            DocumentNode.objects.bulk_create(section_records)
            DocumentNode.objects.bulk_create(topic_records)
            anchors = _anchor_records(version, topic_records)
            _require_unambiguous_ids([*chapter_records, *section_records, *topic_records], anchors)
            ContentAnchor.objects.bulk_create(anchors)
            validate_version_tree(version)
    except (DocumentTreeIntegrityError, DatabaseError) as error:
        return PdfIngestionResult(False, document_id, revision, message=f"Nothing was stored: {error}")

    all_ids = [pid for _, _, ids in assigned for pid in ids] + [sid for sid, _, _ in assigned]
    kept = sum(1 for identifier in all_ids if identifier in previous_ids)
    return PdfIngestionResult(
        success=True,
        document_id=document_id,
        revision=revision,
        sections=len(assigned),
        paragraphs=sum(len(ids) for _, _, ids in assigned),
        kept_ids=kept,
        new_ids=len(all_ids) - kept,
        elapsed_seconds=perf_counter() - started,
    )
